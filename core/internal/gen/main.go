// Command gen writes a Go file holding the given files' contents as one string constant, joined by sep, since Go
// 1.14 has no embed. core/go.sh runs it for the npm polyfills and the Mozilla roots.
//   go run ./internal/gen -pkg fix -name vendorPolyfills -sep '\n;\n' -out fix/polyfills_gen.go FILE...
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io/ioutil"
	"log"
	"path/filepath"
	"strconv"
	"strings"
)

func main() {
	pkg := flag.String("pkg", "", "package of the generated file")
	name := flag.String("name", "", "name of the constant")
	sep := flag.String("sep", `\n`, "separator between the files, with \\n for a newline")
	out := flag.String("out", "", "file to write")
	flag.Parse()

	var parts [][]byte
	var names []string
	for _, path := range flag.Args() {
		names = append(names, filepath.Base(path))
		data, err := ioutil.ReadFile(path)
		if err != nil {
			log.Fatal(err)
		}
		parts = append(parts, data)
	}
	joined := bytes.Join(parts, []byte(strings.Replace(*sep, `\n`, "\n", -1)))
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by core/go.sh from %s. DO NOT EDIT.\n\npackage %s\n\n", strings.Join(names, ", "), *pkg)
	fmt.Fprintf(&b, "const %s = %s\n", *name, strconv.Quote(string(joined)))
	if err := ioutil.WriteFile(*out, b.Bytes(), 0644); err != nil {
		log.Fatal(err)
	}
}
